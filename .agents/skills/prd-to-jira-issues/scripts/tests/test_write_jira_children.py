# ----- CLI -----


class TestCLI:
    def test_happy_path_emits_full_plan(self, tmp_path: Path, run_main):
        doc = _plan_doc(_slice_block("A"))
        plan_path = tmp_path / "PLTPM-99001.md"
        plan_path.write_text(doc, encoding="utf-8")

        code, out, err = run_main(
            wjc.main,
            "--slice-plan",
            str(plan_path),
            "--parent-key",
            "PLTPM-99001",
        )
        assert code == 0
        assert err == ""
        assert out["status"] == "ok"
        assert out["slice_count"] == 1
        assert out["letters"] == ["A"]
        # Spot-check phase 1 + 3 emitted.
        tools = {a["tool"] for a in out["actions"]}
        assert "atlassian.createJiraIssue" in tools
        assert "atlassian.createIssueLink" in tools

    def test_invalid_plan_returns_code_1(self, tmp_path: Path, run_main):
        bad_desc = "## Acceptance criteria\n<!-- TODO -->\n"
        doc = _plan_doc(_slice_block("A", description=bad_desc))
        plan_path = tmp_path / "bad.md"
        plan_path.write_text(doc, encoding="utf-8")
        code, out, _ = run_main(
            wjc.main,
            "--slice-plan",
            str(plan_path),
            "--parent-key",
            "PLTPM-99001",
        )
        assert code == 1
        assert out["status"] == "invalid"
        assert "TODO" in out["reason"]

    def test_missing_file_returns_code_2(self, tmp_path: Path, run_main):
        code, _, err = run_main(
            wjc.main,
            "--slice-plan",
            str(tmp_path / "missing.md"),
            "--parent-key",
            "PLTPM-99001",
        )
        assert code == 2
        assert err


# ----- goldens -----


@pytest.mark.parametrize(
    "name,parent_key",
    [
        ("merchant-health", "PLTPM-99001"),
        ("transfers-v3", "PLTPM-99002"),
    ],
)
class TestActionPlanGoldens:
    """Lock the write_jira_children output for the two reference redlined plans.

    To update: run write_jira_children.py manually against
    `slice-plan-<name>-redlined.md` and replace `<name>.expected.json`.
    """

    def test_action_plan_byte_identical_to_golden(
        self, fixtures_dir: Path, name: str, parent_key: str, run_main
    ):
        plan_path = fixtures_dir / f"slice-plan-{name}-redlined.md"
        expected_path = fixtures_dir / f"{name}.expected.json"

        code, out, _ = run_main(
            wjc.main,
            "--slice-plan",
            str(plan_path),
            "--parent-key",
            parent_key,
        )
        assert code == 0
        actual_text = json.dumps(out, indent=2, ensure_ascii=False) + "\n"
        expected_text = expected_path.read_text(encoding="utf-8")
        assert actual_text == expected_text, (
            f"action plan for {name} drifted from {expected_path}. Regenerate "
            "the fixture if the change is intentional: "
            f"`python write_jira_children.py --slice-plan {plan_path.name} "
            f"--parent-key {parent_key} > tests/fixtures/{name}.expected.json`."
        )

import write_jira_children as wjc

# ----- helpers -----


def _subtask_actions(actions: list[dict]) -> list[dict]:
    """Phase-2 ceremony Sub-task actions.

    `atlassian.createJiraSubtask` doesn't exist on the MCP — the action plan
    emits `atlassian.createJiraIssue` with `issueType="Sub-task"` and a
    top-level `parent` field instead.
    """
    return [
        a
        for a in actions
        if a["tool"] == "atlassian.createJiraIssue"
        and a["args"].get("issueType") == "Sub-task"
    ]


def _slice_create_actions(actions: list[dict]) -> list[dict]:
    """Phase-1 slice-creation actions (everything that is NOT a Sub-task)."""
    return [
        a
        for a in actions
        if a["tool"] == "atlassian.createJiraIssue"
        and a["args"].get("issueType") != "Sub-task"
    ]


def _slice_block(
    letter: str,
    *,
    type_: str = "Task",
    title: str | None = None,
    component: str = "payment-platform",
    depends_on: str = "(none)",
    description: str | None = None,
    modules: str = "Foo, Bar",
    user_stories: str = "1, 2",
    oneliner: str = "do the thing",
) -> str:
    title = title or f"[BE] Slice {letter}"
    description = description or (
        "## What to build (in payment-platform)\n\n"
        "Do the thing.\n\n"
        "## Acceptance criteria\n\n"
        "- [ ] does X\n- [ ] does Y\n"
    )
    indented = "\n".join("  " + line for line in description.splitlines())
    return (
        f"## Slice {letter} — {component}: {oneliner}\n"
        f"- type: {type_}\n"
        f"- title: {title}\n"
        f"- component: {component}\n"
        f"- depends_on: {depends_on}\n"
        f"- modules: {modules}\n"
        f"- user_stories: {user_stories}\n"
        f"- description: |\n{indented}\n"
    )


def _plan_doc(*slice_blocks: str, parent_key: str = "PLTPM-99001") -> str:
    return (
        f"# Slice plan for {parent_key}: test plan\n\n"
        f"> Generated by propose_slices.py from {parent_key} + graphify on 2026-05-02T16:59Z.\n\n"
        + "\n".join(slice_blocks)
    )


# ----- parsing -----


class TestParse:
    def test_parses_single_slice(self):
        doc = _plan_doc(_slice_block("A"))
        slices = wjc.parse_slice_plan(doc)
        assert len(slices) == 1
        s = slices[0]
        assert s["letter"] == "A"
        assert s["type"] == "Task"
        assert s["component"] == "payment-platform"
        assert s["depends_on"] == "(none)"
        assert "Acceptance criteria" in s["description"]

    def test_parses_multiple_slices_in_letter_order(self):
        doc = _plan_doc(
            _slice_block("B", oneliner="b"),
            _slice_block("A", oneliner="a"),
            _slice_block("C", oneliner="c"),
        )
        slices = wjc.parse_slice_plan(doc)
        assert [s["letter"] for s in slices] == ["A", "B", "C"]

    def test_ignores_non_slice_h2_sections(self):
        doc = (
            "# title\n\n"
            "## Notes\n\nirrelevant.\n\n" + _slice_block("A")
        )
        slices = wjc.parse_slice_plan(doc)
        assert len(slices) == 1

    def test_empty_doc_returns_empty_list(self):
        assert wjc.parse_slice_plan("") == []

    def test_parses_depends_on_list(self):
        doc = _plan_doc(_slice_block("A"), _slice_block("B", depends_on="A"))
        slices = wjc.parse_slice_plan(doc)
        # depends_on stays as raw string at parse time; parse_depends_on splits it.
        assert wjc.parse_depends_on(slices[1]["depends_on"]) == ["A"]


class TestParseDependsOn:
    def test_none_literal(self):
        assert wjc.parse_depends_on("(none)") == []

    def test_empty(self):
        assert wjc.parse_depends_on("") == []

    def test_single_letter(self):
        assert wjc.parse_depends_on("A") == ["A"]

    def test_comma_separated(self):
        assert wjc.parse_depends_on("A, B, C") == ["A", "B", "C"]

    def test_strips_whitespace(self):
        assert wjc.parse_depends_on("  A , B  ") == ["A", "B"]


# ----- validation -----


class TestValidate:
    def test_happy_path_passes(self):
        doc = _plan_doc(_slice_block("A"))
        slices = wjc.parse_slice_plan(doc)
        wjc.validate_slices(slices, "PLTPM-99001")

    def test_rejects_empty_plan(self):
        with pytest.raises(wjc.InvalidSlicePlan, match="no slices"):
            wjc.validate_slices([], "PLTPM-99001")

    def test_rejects_missing_required_key(self):
        doc = _plan_doc(_slice_block("A"))
        slices = wjc.parse_slice_plan(doc)
        del slices[0]["component"]
        with pytest.raises(wjc.InvalidSlicePlan, match="missing required key `component`"):
            wjc.validate_slices(slices, "PLTPM-99001")

    def test_rejects_unknown_type(self):
        doc = _plan_doc(_slice_block("A", type_="Bug"))
        slices = wjc.parse_slice_plan(doc)
        with pytest.raises(wjc.InvalidSlicePlan, match="type 'Bug'"):
            wjc.validate_slices(slices, "PLTPM-99001")

    def test_accepts_research_either_form(self):
        # parse_keyvalue_block strips trailing whitespace; we accept both `Research`
        # and `Research ` from PM/eng input. Trailing space is re-applied at emit time.
        for form in ("Research", "Research "):
            doc = _plan_doc(_slice_block("A", type_=form))
            slices = wjc.parse_slice_plan(doc)
            wjc.validate_slices(slices, "PLTPM-99001")

    def test_accepts_design_either_form(self):
        for form in ("Design", "Design "):
            doc = _plan_doc(_slice_block("A", type_=form))
            slices = wjc.parse_slice_plan(doc)
            wjc.validate_slices(slices, "PLTPM-99001")

    def test_rejects_non_canonical_component(self):
        doc = _plan_doc(_slice_block("A", component="random-repo"))
        slices = wjc.parse_slice_plan(doc)
        with pytest.raises(wjc.InvalidSlicePlan, match="not in canonical"):
            wjc.validate_slices(slices, "PLTPM-99001")

    def test_rejects_unresolved_depends_on(self):
        doc = _plan_doc(_slice_block("A", depends_on="Z"))
        slices = wjc.parse_slice_plan(doc)
        with pytest.raises(wjc.InvalidSlicePlan, match="unknown slice 'Z'"):
            wjc.validate_slices(slices, "PLTPM-99001")

    def test_rejects_self_dependency(self):
        doc = _plan_doc(_slice_block("A", depends_on="A"))
        slices = wjc.parse_slice_plan(doc)
        with pytest.raises(wjc.InvalidSlicePlan, match="cannot reference itself"):
            wjc.validate_slices(slices, "PLTPM-99001")

    def test_rejects_TODO_in_description(self):
        bad_desc = (
            "## What to build\n\nDo X.\n\n"
            "## Acceptance criteria\n\n"
            "<!-- TODO: PM/eng must fill in -->\n- [ ] criterion\n"
        )
        doc = _plan_doc(_slice_block("A", description=bad_desc))
        slices = wjc.parse_slice_plan(doc)
        with pytest.raises(wjc.InvalidSlicePlan, match="literal `TODO`"):
            wjc.validate_slices(slices, "PLTPM-99001")

    def test_aggregates_multiple_failures(self):
        bad_desc = "stuff\nTODO here\n"
        doc = _plan_doc(_slice_block("A", type_="Bug", component="x", description=bad_desc))
        slices = wjc.parse_slice_plan(doc)
        with pytest.raises(wjc.InvalidSlicePlan) as exc:
            wjc.validate_slices(slices, "PLTPM-99001")
        msg = str(exc.value)
        assert "type 'Bug'" in msg
        assert "not in canonical" in msg
        assert "literal `TODO`" in msg

    def test_rejects_empty_parent_key(self):
        doc = _plan_doc(_slice_block("A"))
        slices = wjc.parse_slice_plan(doc)
        with pytest.raises(wjc.InvalidSlicePlan, match="parent_key is empty"):
            wjc.validate_slices(slices, "")


